    private static let items: [Item] = {
        var result: [Item] = []
        for line in raw.split(separator: "\n") {
            let parts = line.split(separator: " ", omittingEmptySubsequences: true)
            guard parts.count >= 2, parts[0].count >= 1 else { continue }
            result.append(Item(code: String(parts[0]).lowercased(), word: String(parts[1])))
        }
        return result
    }()

    static func lookup(prefix: String) -> [Item] {
        guard !prefix.isEmpty else { return [] }
        var results: [Item] = []
        for item in items where item.code.hasPrefix(prefix) {
            results.append(item)
            if results.count >= 12 { break }
        }
        return results
    }

    static func exact(_ code: String) -> Item? {
        items.first { $0.code == code }
    }

    static var count: Int { items.count }
