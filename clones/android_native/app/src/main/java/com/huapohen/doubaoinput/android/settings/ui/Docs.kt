豆包输入法（原生复刻）隐私政策

一、我们处理哪些信息
• 键盘输入：拼音、候选、上屏文本。默认在本机处理，用于本地候选与词频学习。
• 个人词库、常用语、剪贴板历史：保存在本机。
• 语音：仅在你主动点击语音按钮时，通过 Android SpeechRecognizer 调用系统语音服务。录音不会写入本应用存储；识别结果会显示在键盘面板中，由你决定插入、编辑或发送。
• AI 写作 / 整理 / 翻译：仅在你主动触发且已配置 API Key 时，将你提供的文本发送至你设置的 Base URL。本应用不内置任何厂商 Key，也不代理或中转请求。
• 设置与账号：本地模拟账号仅保存在本机；不会连接豆包官方账号系统。

二、权限用途
• 麦克风：语音输入。
