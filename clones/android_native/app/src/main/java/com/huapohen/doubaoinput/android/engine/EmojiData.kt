/** Small indirection so emoji recents live in the existing prefs without extra dependencies. */
object PrefsHelper {
    fun recentEmojis(): List<String> {
        val arr = com.huapohen.doubaoinput.android.core.Prefs.getJsonArray("emoji_recent")
        val out = mutableListOf<String>()
        for (i in 0 until arr.length()) out.add(arr.optString(i))
        return out
    }
    fun addRecentEmoji(e: String) {
        val list = recentEmojis().toMutableList()
        list.remove(e); list.add(0, e)
        val arr = org.json.JSONArray(); list.take(24).forEach { arr.put(it) }
        com.huapohen.doubaoinput.android.core.Prefs.putJson("emoji_recent", arr)
    }
}
